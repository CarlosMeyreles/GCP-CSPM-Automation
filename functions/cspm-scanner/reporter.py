"""
reporter.py — Pack it up and ship it: JSON + CSV to GCS, rows to BigQuery.

Three sinks with INDEPENDENT failure modes:
    1. GCS JSON — machine-readable full detail
    2. GCS CSV — human-readable flat table
    3. BigQuery streaming inserts — queryable within seconds

Partial-write tolerance: if one sink fails, the others still complete.
A transient BQ hiccup shouldn't lose a GCS report (and vice versa).

Content-addressed naming: every GCS file includes timestamp + scan_id so
repeat invocations never overwrite past reports — enterprise audit standard.
"""

import csv
import io
import json
import logging
from datetime import datetime, timezone
from typing import List, Dict, Any

from google.cloud import storage
from google.cloud import bigquery
from google.api_core import exceptions as google_exceptions

from scanner import Finding
from remediator import RemediationAction

logger = logging.getLogger(__name__)


# =============================================================================
# PUBLIC ENTRY POINT — called by main.py after scanner + classifier + remediator
# =============================================================================
def report(
    scan_id: str,
    scan_timestamp: datetime,
    project_id: str,
    reports_bucket: str,
    bq_dataset: str,
    findings: List[Finding],
    classified: Dict[str, Any],
    remediations: List[RemediationAction],
) -> Dict[str, Any]:
    """
    Write JSON, CSV, and BigQuery outputs for a single scan.

    Args:
        scan_id: UUID generated by main.py at scan start.
        scan_timestamp: UTC datetime of when the scan started.
        project_id: GCP project ID being scanned.
        reports_bucket: GCS bucket to write JSON/CSV reports to.
        bq_dataset: BigQuery dataset for scan_history + remediation_log.
        findings: Full list from scanner.py.
        classified: Dict from classifier.py.
        remediations: List of RemediationAction records from remediator.py.

    Returns:
        Dict summarizing what was written to each sink. Includes any errors.
    """
    results = {
        "scan_id": scan_id,
        "gcs_json": None,
        "gcs_csv": None,
        "bq_scan_history_rows": 0,
        "bq_remediation_log_rows": 0,
        "errors": [],
    }

    # Build the full JSON report ONCE in memory, write to both sinks.
    report_payload = _build_json_report(
        scan_id, scan_timestamp, project_id, findings, classified, remediations
    )

    # ---- Sink 1: GCS JSON ----
    try:
        gcs_json_name = _write_gcs_json(
            reports_bucket, scan_id, scan_timestamp, report_payload
        )
        results["gcs_json"] = f"gs://{reports_bucket}/{gcs_json_name}"
        logger.info("Wrote JSON report: %s", results["gcs_json"])
    except Exception as e:
        logger.exception("GCS JSON write failed: %s", e)
        results["errors"].append(f"gcs_json: {e}")

    # ---- Sink 2: GCS CSV ----
    try:
        gcs_csv_name = _write_gcs_csv(
            reports_bucket, scan_id, scan_timestamp, findings, remediations
        )
        results["gcs_csv"] = f"gs://{reports_bucket}/{gcs_csv_name}"
        logger.info("Wrote CSV report: %s", results["gcs_csv"])
    except Exception as e:
        logger.exception("GCS CSV write failed: %s", e)
        results["errors"].append(f"gcs_csv: {e}")

    # ---- Sink 3a: BigQuery scan_history ----
    try:
        rows_inserted = _write_bq_scan_history(
            project_id, bq_dataset, scan_id, scan_timestamp,
            findings, remediations,
        )
        results["bq_scan_history_rows"] = rows_inserted
        logger.info("Inserted %d row(s) into scan_history", rows_inserted)
    except Exception as e:
        logger.exception("BQ scan_history insert failed: %s", e)
        results["errors"].append(f"bq_scan_history: {e}")

    # ---- Sink 3b: BigQuery remediation_log ----
    try:
        rows_inserted = _write_bq_remediation_log(
            project_id, bq_dataset, scan_id, scan_timestamp, remediations
        )
        results["bq_remediation_log_rows"] = rows_inserted
        logger.info("Inserted %d row(s) into remediation_log", rows_inserted)
    except Exception as e:
        logger.exception("BQ remediation_log insert failed: %s", e)
        results["errors"].append(f"bq_remediation_log: {e}")

    return results


# =============================================================================
# JSON report builder — single source of truth for the full scan payload
# =============================================================================
def _build_json_report(
    scan_id: str,
    scan_timestamp: datetime,
    project_id: str,
    findings: List[Finding],
    classified: Dict[str, Any],
    remediations: List[RemediationAction],
) -> Dict[str, Any]:
    """Build the canonical JSON report. Reused by GCS JSON write."""
    return {
        "scan_id": scan_id,
        "scan_timestamp": scan_timestamp.isoformat(),
        "project_id": project_id,
        "summary": {
            "total_findings": classified["total_count"],
            "by_severity": {
                sev: info["count"]
                for sev, info in classified["by_severity"].items()
                if info["count"] > 0
            },
            "by_category": {
                cat: info["count"]
                for cat, info in classified["by_category"].items()
            },
            "total_remediations_attempted": len(remediations),
            "total_remediations_successful": sum(1 for r in remediations if r.success),
            "dry_run_count": sum(1 for r in remediations if r.dry_run),
        },
        "findings": [
            {
                "finding_id": f.finding_id,
                "resource_name": f.resource_name,
                "category": f.category,
                "severity": f.severity,
                "state": f.state,
                "details": f.details,
            }
            for f in findings
        ],
        "remediations": [r.to_dict() for r in remediations],
    }


# =============================================================================
# Sink 1: GCS JSON write
# -----------------------------------------------------------------------------
# Content-addressed name: reports/YYYY-MM-DD/scan-<scan_id>.json
# Date prefix makes partition-style queries easy (gsutil ls on one day).
# =============================================================================
def _write_gcs_json(
    reports_bucket: str,
    scan_id: str,
    scan_timestamp: datetime,
    payload: Dict[str, Any],
) -> str:
    """Write the JSON report to GCS. Returns the object name."""
    client = storage.Client()
    bucket = client.bucket(reports_bucket)

    date_prefix = scan_timestamp.strftime("%Y-%m-%d")
    object_name = f"reports/{date_prefix}/scan-{scan_id}.json"

    blob = bucket.blob(object_name)
    blob.upload_from_string(
        data=json.dumps(payload, indent=2, default=str),
        content_type="application/json",
    )
    return object_name


# =============================================================================
# Sink 2: GCS CSV write
# -----------------------------------------------------------------------------
# One row per finding, with columns flattened for spreadsheet consumption.
# =============================================================================
def _write_gcs_csv(
    reports_bucket: str,
    scan_id: str,
    scan_timestamp: datetime,
    findings: List[Finding],
    remediations: List[RemediationAction],
) -> str:
    """Write the CSV summary to GCS. Returns the object name."""
    client = storage.Client()
    bucket = client.bucket(reports_bucket)

    date_prefix = scan_timestamp.strftime("%Y-%m-%d")
    object_name = f"reports/{date_prefix}/scan-{scan_id}.csv"

    # Build a lookup of remediations keyed by finding_id for the join.
    remediation_by_finding = {r.finding_id: r for r in remediations}

    # Write to an in-memory buffer, then upload once.
    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow([
        "scan_id", "scan_timestamp", "finding_id", "resource_name",
        "category", "severity", "state",
        "remediated", "remediation_action", "remediation_dry_run",
    ])

    for f in findings:
        rem = remediation_by_finding.get(f.finding_id)
        writer.writerow([
            scan_id,
            scan_timestamp.isoformat(),
            f.finding_id,
            f.resource_name,
            f.category,
            f.severity,
            f.state,
            "true" if (rem and rem.success and not rem.dry_run) else "false",
            rem.action_type if rem else "",
            "true" if (rem and rem.dry_run) else "false",
        ])

    blob = bucket.blob(object_name)
    blob.upload_from_string(
        data=buffer.getvalue(),
        content_type="text/csv",
    )
    return object_name


# =============================================================================
# Sink 3a: BigQuery scan_history insert
# -----------------------------------------------------------------------------
# One row per finding. Streaming insert for near-real-time queryability.
# =============================================================================
def _write_bq_scan_history(
    project_id: str,
    bq_dataset: str,
    scan_id: str,
    scan_timestamp: datetime,
    findings: List[Finding],
    remediations: List[RemediationAction],
) -> int:
    """Insert one row per finding into scan_history. Returns row count."""
    client = bigquery.Client(project=project_id)
    table_id = f"{project_id}.{bq_dataset}.scan_history"

    remediation_by_finding = {r.finding_id: r for r in remediations}
    ts_iso = scan_timestamp.isoformat()

    rows = []
    for f in findings:
        rem = remediation_by_finding.get(f.finding_id)
        rows.append({
            "scan_id": scan_id,
            "timestamp": ts_iso,
            "finding_id": f.finding_id,
            "resource_name": f.resource_name,
            "finding_category": f.category,
            "severity": f.severity,
            "state": f.state,
            "remediated": bool(rem and rem.success and not rem.dry_run),
            "remediation_action": rem.action_type if rem else None,
        })

    if not rows:
        return 0

    errors = client.insert_rows_json(table_id, rows)
    if errors:
        # BigQuery streaming returns PER-ROW errors in a list; raise so caller logs.
        raise google_exceptions.GoogleAPIError(f"BQ errors: {errors}")

    return len(rows)


# =============================================================================
# Sink 3b: BigQuery remediation_log insert
# -----------------------------------------------------------------------------
# One row per RemediationAction. Captures full before/after audit trail.
# =============================================================================
def _write_bq_remediation_log(
    project_id: str,
    bq_dataset: str,
    scan_id: str,
    scan_timestamp: datetime,
    remediations: List[RemediationAction],
) -> int:
    """Insert one row per remediation action into remediation_log."""
    client = bigquery.Client(project=project_id)
    table_id = f"{project_id}.{bq_dataset}.remediation_log"

    ts_iso = scan_timestamp.isoformat()

    rows = []
    for r in remediations:
        rows.append({
            "remediation_id": f"{scan_id}-{r.finding_id}",  # Deterministic ID
            "timestamp": ts_iso,
            "scan_id": scan_id,
            "finding_id": r.finding_id,
            "resource_name": r.resource_name,
            "action_type": r.action_type,
            "dry_run": r.dry_run,
            "before_state": r.before_state,
            "after_state": r.after_state,
            "success": r.success,
            "error_message": r.error_message,
        })

    if not rows:
        return 0

    errors = client.insert_rows_json(table_id, rows)
    if errors:
        raise google_exceptions.GoogleAPIError(f"BQ errors: {errors}")

    return len(rows)
